function plPlural(n, one, few, many) {
  const m10 = n % 10, m100 = n % 100;
  const w = n === 1 ? one : m10 >= 2 && m10 <= 4 && !(m100 >= 12 && m100 <= 14) ? few : many;
  return `${n.toLocaleString('pl')} ${w}`;
}

